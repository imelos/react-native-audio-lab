export type WaveformType = 'sine' | 'saw' | 'square' | 'triangle' | 'pulse';

export type PresetCategory =
  | 'Keys'
  | 'Pads'
  | 'Bass'
  | 'Leads'
  | 'Plucks'
  | 'Bells'
  | 'EDM'
  | 'Analog'
  | 'Ambient'
  | 'Cinematic';

export interface SynthPreset {
  name: string;
  category: PresetCategory;

  // Oscillator 1
  waveform1: WaveformType;
  detuneCents1: number;

  // Oscillator 2
  waveform2: WaveformType;
  detuneCents2: number;
  osc2Level: number; // 0-1
  osc2Semi: number; // -24 to +24

  // Sub-oscillator
  subLevel: number; // 0-1

  // Noise
  noiseLevel: number; // 0-1

  // Per-voice filter
  filterEnabled: boolean;
  filterCutoff: number; // Hz
  filterResonance: number; // 0-1
  filterEnvAmount: number; // 0-1

  // ADSR
  attack: number;
  decay: number;
  sustain: number;
  release: number;

  // Volume
  volume: number;

  // Advanced synthesis (optional — defaults applied at native layer)
  pulseWidth?: number;        // 0.0-1.0; default 0.5
  unisonCount?: number;       // 1-8; default 1
  unisonSpread?: number;      // 0-100 cents; default 20
  glideTime?: number;         // 0-5 seconds; default 0
  lfoRate?: number;           // 0.1-20 Hz; default 1
  lfoDepth?: number;          // 0-1; default 0
  lfoDestination?: number;    // 0=pitch, 1=filter, 2=volume; default 0
  lfoWaveform?: WaveformType; // default 'sine'

  // Post-effects (optional)
  effects?: Array<{
    type: 'reverb' | 'delay' | 'filter' | 'chorus' | 'distortion' | 'compressor';
    params: Record<string, number>;
  }>;
}

